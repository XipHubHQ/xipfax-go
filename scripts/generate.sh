#!/bin/sh
# Makes the SDK from openapi.json, the API's document: scripts/sdk-document.jq writes the document
# it is generated from, openapi-generator 7.17.0 generates the client from that with
# openapi-generator.yaml, this script writes api_version.go from the document's info.version, and
# gofmt formats them all. Nothing it writes is edited by hand.
set -eu
cd "$(dirname "$0")/.."

generator=$(openapi-generator version)
if [ "$generator" != "7.17.0" ]; then
  echo "scripts/generate.sh takes openapi-generator 7.17.0, and this machine has $generator." >&2
  exit 1
fi

if ! version=$(jq -er '.info.version | select(test("^[0-9]{4}-[0-9]{2}-[0-9]{2}$"))' openapi.json); then
  echo "openapi.json's info.version is not a day, as 2026-11-03 is." >&2
  exit 1
fi

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
jq -f scripts/sdk-document.jq openapi.json > "$work/openapi.json"

# The Go files the last run wrote go first, so that one the document no longer makes doesn't stay.
if [ -f .openapi-generator/FILES ]; then
  grep -E '^[A-Za-z0-9_]+\.go$' .openapi-generator/FILES | while IFS= read -r file; do
    rm -f "./$file"
  done
fi

openapi-generator generate -g go -i "$work/openapi.json" -o . -c openapi-generator.yaml

cat > api_version.go <<EOF
// Code generated by scripts/generate.sh from openapi.json's info.version. DO NOT EDIT.

package xipfax

// APIVersion is the version of XipFax's API this SDK is generated from, which every request names
// in its Xip-Version header.
const APIVersion = "$version"
EOF

gofmt -w api_version.go $(grep -E '^[A-Za-z0-9_]+\.go$' .openapi-generator/FILES)
